export function getTranslation(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const localeMap = translations[locale] ?? translations.en;
  let text = localeMap[key] ?? translations.en[key] ?? key;

  if (params) {
    for (const [paramKey, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{\\{\\s*${paramKey}\\s*\\}\\}`, 'g'), String(value));
    }
  }

  return text;
}

